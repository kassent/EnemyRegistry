static std::array<uint8_t, 0x2000> nativeCapacityCode{};
static ci::Type nativeFactoryType{};
static bool CheckEnemyRegistrationPatchValidation() {
    const ci::ProviderContext noTypes{[](const char*) -> const ci::Type* {
                                  return nullptr;
                              },
                              [](const ci::Type*, const char*) -> void* {
                                  return nullptr;
                              }};
    const ci::ProviderContext noMethods{[](const char*) -> const ci::Type* {
                                    return &nativeFactoryType;
                                },
                                noTypes.GetMethod};
    const ci::ProviderContext noCapacityPattern{
        .GetType = noMethods.GetType,
        .GetMethod = [](const ci::Type*, const char*) -> void* {
            return nativeCapacityCode.data();
        },
        .CreateString = [](void*, const char*) -> void* {
            return nullptr;
        },
        .IsDerivedFrom = [](const ci::Type* type, const ci::Type* baseType) {
            return type && type == baseType;
        }};
    nativeCapacityCode.fill(0x90);
    for (const auto* context : {static_cast<const ci::ProviderContext*>(nullptr), &noTypes, &noMethods, &noCapacityPattern}) {
        if (EnemyRegistry::RegistrationHooks::InstallHooks(context))
            return false;
    }
    for (const auto& context : {ci::ProviderContext{nullptr, noTypes.GetMethod}, ci::ProviderContext{noMethods.GetType, nullptr}}) {
        if (EnemyRegistry::RegistrationHooks::InstallHooks(&context))
            return false;
    }
    // 所有容量契约核对完才写补丁：缺失模式时，整段模拟代码应保持原样。
    return std::ranges::all_of(nativeCapacityCode, [](uint8_t value) {
        return value == 0x90;
    });
}

